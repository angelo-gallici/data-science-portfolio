def limpiar_texto(texto):
    if isinstance(texto, str):
        # Eliminar tildes
        texto = unicodedata.normalize('NFKD', texto).encode('ASCII', 'ignore').decode('utf-8')
        # Poner en mayúsculas
        texto = texto.upper()
    return texto

